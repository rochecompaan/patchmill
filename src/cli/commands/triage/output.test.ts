import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test, type TestContext } from "node:test";
import {
  FakeHost,
  writeFakeHostState,
} from "../../../../test-support/fake-host.ts";
import { CONFIG_FILE } from "../../../config/config.ts";
import type { Issue } from "../../../host/types.ts";
import { runTriage } from "../../../kernel/triage.ts";
import { main } from "./main.ts";

function issue(number: number, labels: string[] = []): Issue {
  return {
    number,
    labels,
    title: number === 9 ? "Votes disappear on refresh" : "Add social features",
    body: "Details",
    author: "reporter",
    state: "open",
    url: `https://example.invalid/issues/${number}`,
    createdAt: "2026-10-01",
    comments: [],
  };
}

function result(label: string, comment = "") {
  return `\`\`\`json\n${JSON.stringify({ label, comment })}\n\`\`\``;
}

async function harness(t: TestContext, issues: Issue[], responses: string[]) {
  const root = await fs.mkdtemp(join(tmpdir(), "patchmill-triage-output-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  await fs.writeFile(
    join(root, CONFIG_FILE),
    JSON.stringify({ labels: { ready: "queue" } }),
  );
  const state = join(root, "host.json");
  writeFakeHostState(state, { issues });
  const host = new FakeHost(state);
  const script = join(root, "pi.mjs");
  await fs.writeFile(
    script,
    `import fs from 'node:fs';
const root = ${JSON.stringify(root)};
fs.appendFileSync(root + '/launches', 'started\\n');
const index = fs.readFileSync(root + '/launches', 'utf8').trim().split('\\n').length - 1;
console.error('Pi diagnostic');
console.log(${JSON.stringify(responses)}[index]);
`,
  );
  const stdout: string[] = [],
    stderr: string[] = [];
  // Capture direct writes too: the regression bypassed the injected CLI output.
  for (const [stream, chunks] of [
    [process.stdout, stdout],
    [process.stderr, stderr],
  ] as const) {
    t.mock.method(stream, "write", (chunk: string, callback?: () => void) => {
      chunks.push(String(chunk));
      callback?.();
      return true;
    });
  }
  return {
    root,
    host,
    stdout,
    stderr,
    run: (args: string[] = []) =>
      main(args, {
        repoRoot: root,
        output: {
          stdout: (line) => stdout.push(line),
          stderr: (line) => stderr.push(line),
        },
        runner: async () => ({ code: 0, stdout: "", stderr: "" }),
        // Keep the CLI, kernel, supervisor, and filesystem real. Only the external
        // host and paid Pi process are replaced with local deterministic fixtures.
        runTriage: (config, deps, options) =>
          runTriage(
            config,
            {
              ...deps,
              host,
              piCommand: { command: process.execPath, argsPrefix: [script] },
            },
            options,
          ),
      }),
  };
}

// Removing the CLI reporter or letting the supervisor stream raw output must
// fail this test, even when classification and host mutations still succeed.
test("triage shows per-issue progress instead of model JSON and retains raw session logs", async (t) => {
  const comment = [
    "> _This was generated by AI during triage._",
    "Please provide reproduction steps.",
    "Which browser did you use?",
    "Does an ordinary refresh lose votes?",
    "Which app version is affected?",
    "Sixth preview line must stay in the log.",
  ].join("\n");
  const first = result("needs-info", comment);
  const f = await harness(
    t,
    [issue(9, ["bug"]), issue(10, ["enhancement"])],
    [first, result("queue")],
  );
  assert.equal(await f.run(), 0);
  const text = f.stdout.join("\n");
  assert.doesNotMatch(text, /```json|"label"|Pi diagnostic/);
  assert.match(text, /^> patchmill triage\n/);
  assert.match(text, /issues: 2/);
  assert.match(text, /#9 Votes disappear on refresh/);
  assert.match(text, /link: https:\/\/example.invalid\/issues\/9/);
  assert.match(text, /labels: bug -> bug, needs-info/);
  assert.match(
    text,
    /comment added:\n {2}> _This was generated by AI during triage\._/,
  );
  assert.match(text, /Which app version is affected\?/);
  assert.doesNotMatch(text, /Sixth preview line/);
  assert.match(text, /progress: 1\/2 triaged/);
  assert.match(text, /#10 Add social features/);
  assert.match(text, /labels: enhancement -> enhancement, queue/);
  assert.doesNotMatch(text.slice(text.indexOf("#10")), /comment(?: added)?:/);
  assert.match(text, /progress: 2\/2 triaged/);
  assert.match(text, /agent issue triage: applied/);
  assert.ok(text.indexOf("progress: 1/2") < text.indexOf("#10"));
  assert.deepEqual(f.stderr, []);
  assert.deepEqual(
    f.host.state().issues.map((i) => i.labels),
    [
      ["bug", "needs-info"],
      ["enhancement", "queue"],
    ],
  );
  const logs = [...text.matchAll(/log: (.+\/session-1\.log)/g)].map(
    (m) => m[1]!,
  );
  assert.equal(logs.length, 2);
  const raw = await fs.readFile(logs[0]!, "utf8");
  assert.ok(raw.includes(first));
  assert.match(raw, /Pi diagnostic/);
});

test("dry-run previews label changes and comments without claiming or making host writes", async (t) => {
  const f = await harness(
    t,
    [issue(9, ["needs-info", "bug"])],
    [result("queue", "Ready to implement.")],
  );
  const before = f.host.state().issues;
  assert.equal(await f.run(["--issue", "9", "--dry-run"]), 0);
  const text = f.stdout.join("\n");
  assert.match(text, /> patchmill triage --issue 9 --dry-run/);
  assert.match(text, /labels: needs-info, bug -> bug, queue/);
  assert.match(text, /comment:\n {2}Ready to implement\./);
  assert.match(text, /agent issue triage: dry-run/);
  assert.doesNotMatch(text, /comment added:|```json|"label"/);
  assert.deepEqual(f.host.state().issues, before);
  assert.equal(
    f.host.state().calls.some((c) => /setLabels|commentIssue/.test(c)),
    false,
  );
});

test("no candidates displays an explicit no-issues summary without starting Pi", async (t) => {
  const f = await harness(t, [issue(9, ["queue"])], []);
  assert.equal(await f.run(), 0);
  assert.match(f.stdout.join("\n"), /issues: 0/);
  assert.match(f.stdout.join("\n"), /agent issue triage: no-issues/);
  await assert.rejects(fs.stat(join(f.root, "launches")), { code: "ENOENT" });
});

test("an invalid result keeps issue context and warns while independent issues continue", async (t) => {
  const f = await harness(
    t,
    [issue(9), issue(10)],
    ["not a result", result("queue")],
  );
  assert.equal(await f.run(), 0);
  const text = f.stdout.join("\n");
  assert.match(text, /#9 Votes disappear on refresh/);
  assert.match(text, /#10 Add social features/);
  assert.match(text, /labels: \(none\) -> queue/);
  assert.match(text, /agent issue triage: partial/);
  assert.doesNotMatch(text, /not a result|```json/);
  assert.match(f.stderr.join("\n"), /Warning: Issue #9:/);
  assert.deepEqual(
    f.host.state().issues.map((i) => i.labels),
    [[], ["queue"]],
  );
});
